"""Subset Pretendard Variable (SIL OFL 1.1, https://github.com/orioncactus/pretendard) for the Korean pages.

  uv run --with 'fonttools[woff]' python -I scripts/build-pretendard.py /path/to/PretendardVariable.woff2

Why two files: the page copy uses a few hundred Hangul syllables. They go into Pretendard-ko-core.woff2, which is the
only Korean font file a visitor downloads. Every other syllable of KS X 1001 (the 2,350 common ones) goes into
Pretendard-ko-rest.woff2, declared first with a broad unicode-range, so it is fetched only when someone edits the copy
and uses a syllable that is not in core yet. Re-run this script after changing src/content/*.ts; test/fonts.test.ts
fails when a syllable of the copy is missing from core.

Both files keep only the weight axis range 400-700 (the site uses 400-700). English pages never load them: the
unicode-range does not match any character on those pages (Geist covers Latin).
"""
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
out_fonts = root / 'src' / 'assets' / 'fonts'

# Characters the site can show: every content file (copy in both languages) plus the site's own strings.
text = ''.join(p.read_text(encoding='utf8') for p in [*sorted((root / 'src' / 'content').glob('*.ts')), root / 'src' / 'site.ts'])
text += ''.join(p.read_text(encoding='utf8') for p in sorted((root / 'src' / 'components').glob('*.astro')))
core = {ord(c) for c in text if ord(c) >= 0x20 and c not in '​'} | set(range(0x20, 0x7F))
core = {c for c in core if c >= 0x20}

# KS X 1001 Hangul: the 2,350 syllables that encode in EUC-KR, plus compatibility Jamo.
ksx = set()
for cp in range(0xAC00, 0xD7A4):
    try:
        b = chr(cp).encode('euc_kr')
    except UnicodeEncodeError:
        continue
    # Rows 0xB0-0xC8 of KS X 1001 are the 2,350 common syllables (Python's euc_kr also encodes the rarer ones).
    if len(b) == 2 and 0xB0 <= b[0] <= 0xC8 and 0xA1 <= b[1] <= 0xFE:
        ksx.add(cp)
jamo = set(range(0x3131, 0x318F))
rest = (ksx | jamo) - core


def ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], None, None
    for cp in cps:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


def limited_font():
    # Cut the weight axis to 400-700 once, then reload the result (subsetting a lazily loaded font breaks gvar).
    font = TTFont(str(src))
    instancer.instantiateVariableFont(font, {'wght': (400, 700)}, inplace=True)
    buf = io.BytesIO()
    font.flavor = None
    font.save(buf)
    buf.seek(0)
    return buf.getvalue()


LIMITED = None


def build(cps, name):
    global LIMITED
    if LIMITED is None:
        LIMITED = limited_font()
    font = TTFont(io.BytesIO(LIMITED), lazy=False)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'locl', 'ccmp']
    opts.notdef_outline = True
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    s = subset.Subsetter(opts)
    s.populate(unicodes=sorted(cps))
    s.subset(font)
    font.flavor = 'woff2'
    path = out_fonts / name
    font.save(str(path))
    print(f'{name}: {len(cps)} characters, {path.stat().st_size / 1024:.0f} KB')


# Only keep Hangul in rest (punctuation and Latin come from core / Geist).
build(core, 'Pretendard-ko-core.woff2')
build(rest, 'Pretendard-ko-rest.woff2')

# Characters of the copy that Hangul-only unicode-range lists must cover, for the CSS and the test.
hangul_core = sorted(c for c in core if 0xAC00 <= c <= 0xD7A3 or 0x3131 <= c <= 0x318E)
(root / 'src' / 'assets' / 'fonts' / 'pretendard-core-chars.txt').write_text(''.join(chr(c) for c in hangul_core), encoding='utf8')

css = f"""/* Generated by scripts/build-pretendard.py. Do not edit.
   Declared in this order on purpose: the later face wins for the characters it lists, so the small "core" file serves
   every syllable the copy uses and the "rest" file is only fetched for a syllable that is not in core yet. */
@font-face {{
  font-family: "Pretendard";
  src: url("../assets/fonts/Pretendard-ko-rest.woff2") format("woff2");
  font-weight: 400 700; font-style: normal; font-display: swap;
  unicode-range: U+AC00-D7A3, U+3131-318E;
}}
@font-face {{
  font-family: "Pretendard";
  src: url("../assets/fonts/Pretendard-ko-core.woff2") format("woff2");
  font-weight: 400 700; font-style: normal; font-display: swap;
  unicode-range: {ranges(core)};
}}
"""
(root / 'src' / 'styles' / 'fonts-pretendard.css').write_text(css, encoding='utf8')
print('core hangul/jamo:', len(hangul_core), ' rest:', len(rest))
